//! Two-phase MCP auth tools.
//!
//! MCP calls must not block for many minutes while a human completes an
//! interactive browser login. Therefore login is split into:
//!
//!   1. `auth_login_start`  — AUP-enforce, spawn the `rev-auth login` helper
//!      subprocess in headed mode, return an opaque `session_token`.
//!   2. `auth_login_complete` — poll for the helper to finish (or a marker
//!      file to appear), then read back ONLY `ProfileMeta` from the on-disk
//!      `AuthStore` and return that. Cookie values are NEVER materialized in
//!      MCP responses; this module never calls `AuthStore::load`.
//!
//! Plus two read-only tools:
//!
//!   * `auth_list`   — `ProfileMeta` summary, no values.
//!   * `auth_status` — freshness classification per profile.
//!
//! Delete is intentionally NOT exposed over MCP (CLI-only, requires TTY
//! confirmation per Phase 9d).

